    private void SubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SubmitActionPerformed
        String firstName = FirstName.getText();
        String lastName = LastName.getText();
        int Age = (int) ageSpinner.getValue();
        String Email = Email1.getText();
        String Gender = (String) Gendercombobox.getSelectedItem();
        String Phone = textPhoneNumber.getText();
        String Continent = (String) ContinentComboBox.getSelectedItem();
        String Experience = Hobby.getText();
        String Photo = Photo1.getText();

        String errorTitle = "Ooops";

        // Validate first name
        if (firstName == null || firstName.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Invalid First Name Provided", errorTitle, JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validate last name
        if (lastName == null || lastName.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Invalid Last Name Provided", errorTitle, JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validate phone
        if (!Phone.matches("\\d{3}-\\d{3}-\\d{4}")) {
            JOptionPane.showMessageDialog(this, "Invalid Phone Number", errorTitle, JOptionPane.ERROR_MESSAGE);
            return;
        }

        //validate email
        if (!Email.matches("^[\\w-\\.]+@([\\w-]+\\.)+[\\w-]{2,4}$")) {
            JOptionPane.showMessageDialog(this, "Invalid email format!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        //creating the new user
        User newUser = new User(firstName,lastName,Gender,Age,Phone,Email,Continent,Experience,Photo);

        //building message for success pop up
        String message= "FirstName: " + firstName
        +"\n LastName:"+lastName
        +"\n Age:"+Age
        +"\n Gender"+Gender
        +"\n Phone"+Phone
        + "\n Email: " + Email
        +"\n Continent"+Continent
        +"\n Hobbies"+Experience;

        //uploaded image showing
        ImageIcon photoIcon = null;
        if (Photo != null && !Photo.trim().isEmpty()) {
            ImageIcon rawIcon = new ImageIcon(Photo);
            Image scaled = rawIcon.getImage().getScaledInstance(150, 150, Image.SCALE_SMOOTH);
            photoIcon = new ImageIcon(scaled);
        }
        
        //call form complete on the main frame
        MainJFrame frame = (MainJFrame) javax.swing.SwingUtilities.getWindowAncestor(this);
        frame.formComplete(newUser);
        
        //success option dialog
        JOptionPane.showMessageDialog(
            this,
            message,
            "Success",
            JOptionPane.INFORMATION_MESSAGE,
            photoIcon
        );

    }//GEN-LAST:event_SubmitActionPerformed

