    private void UploadPhotoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UploadPhotoActionPerformed

        JFileChooser chooser = new JFileChooser();
        int result = chooser.showOpenDialog(this);
        if (result == JFileChooser.APPROVE_OPTION) {
            File selectedFile = chooser.getSelectedFile();
            Photo1.setText(selectedFile.getAbsolutePath());

            // Load and scale image to fit label
            ImageIcon icon = new ImageIcon(selectedFile.getAbsolutePath());
            Image scaledImage = icon.getImage().getScaledInstance(photoUpload.getWidth(), photoUpload.getHeight(), Image.SCALE_SMOOTH);
            icon = new ImageIcon(scaledImage);

            photoUpload.setIcon(icon);
            photoUpload.setText(""); // remove placeholder text
        }
    }//GEN-LAST:event_UploadPhotoActionPerformed

    private void jCalendarComboBox1StateChanged(javax.swing.event.ChangeEvent evt) {//GEN-FIRST:event_jCalendarComboBox1StateChanged

        java.util.Calendar c = jCalendarComboBox1.getCalendar();
        java.util.Calendar today = java.util.Calendar.getInstance();
        
        //calculate age
        int age = today.get(java.util.Calendar.YEAR) - c.get(java.util.Calendar.YEAR);
        
        // age validation
        if (age <= 0) {
            JOptionPane.showMessageDialog(this, "Invalid Age", "Age", JOptionPane.ERROR_MESSAGE);
            return;
        }

        //set age
        ageSpinner.setValue(age);
    }//GEN-LAST:event_jCalendarComboBox1StateChanged


